#[derive(Debug, Default, OssRequestModel)]
pub struct ProcessObjectRequest {
    /// The name of the bucket.
    pub bucket: String,

    /// The name of the object.
    pub key: String,

    /// Image processing parameters, for example
    /// `image/resize,m_fixed,w_100,h_100`.
    pub process: String,

    /// To indicate that the requester is aware that the request and data
    /// download will incur costs
    #[field(type = "header", rename = "x-oss-request-payer")]
    pub request_payer: Option<String>,

    pub common: RequestCommon,
}

#[derive(Debug, Default, Deserialize, OssResultModel)]
pub struct ProcessObjectResult {
    /// The name of the bucket.
    #[serde(default)]
    pub bucket: String,

    /// The size of the processed object.
    #[serde(default, rename = "fileSize")]
    pub file_size: i64,

    /// The name of the processed object.
    #[serde(default)]
    pub object: String,

    /// The status of the process operation.
    #[serde(default, rename = "status")]
    pub process_status: String,

    /// Common result fields
    #[serde(skip)]
    pub common: ResultCommon,
}

impl Client {
    /// Applies a process on the specified image file.
    ///
    /// # Arguments
    ///
    /// * `request` - The `ProcessObjectRequest` containing the bucket name,
    ///   object key and the process parameters.
    ///
    /// # Examples
    ///
    /// ```no_run
    /// # use alibabacloud_oss_sdk_rust_v2::api::object::ProcessObjectRequest;
    /// # use alibabacloud_oss_sdk_rust_v2::client::Client;
    /// # use alibabacloud_oss_sdk_rust_v2::config::Config;
    /// #
    /// # tokio_test::block_on(async {
    /// let client = Client::new(&Config::default());
    /// let request = ProcessObjectRequest {
    ///     bucket: "my-bucket".to_string(),
    ///     key: "my-image.jpg".to_string(),
    ///     process: "image/resize,m_fixed,w_100,h_100|saveas,o_thumbnail.jpg".to_string(),
    ///     ..Default::default()
    /// };
    ///
    /// match client.process_object(&request).await {
    ///     Ok(result) => {
    ///         println!("Process status: {}", result.process_status);
    ///     }
    ///     Err(error) => {
    ///         eprintln!("Failed to process object: {}", error);
    ///     }
    /// }
    /// # })
    /// ```
    pub async fn process_object(
        &self,
        request: &ProcessObjectRequest,
    ) -> Result<ProcessObjectResult, Box<dyn std::error::Error + Send + Sync>> {
        let mut input = OperationInput {
            op_name: "ProcessObject".to_string(),
            method: http::Method::POST,
            bucket: Some(request.bucket.clone()),
            key: Some(request.key.clone()),
            parameters: [("x-oss-process", request.process.as_str())]
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect(),
            ..Default::default()
        };

        modify_request(
            &mut input,
            request.header_map(),
            request.query_map(),
            vec![update_content_md5],
        )?;

        let mut output = self.invoke_operation(input, vec![]).await?;

        // The response body is JSON.
        let body_data = output.get_all_data().await?;
        let mut result: ProcessObjectResult = serde_json::from_slice(&body_data)?;
        result.update_result(&output);

        Ok(result)
    }
}

