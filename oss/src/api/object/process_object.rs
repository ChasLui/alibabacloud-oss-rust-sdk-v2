    #[test]
    fn test_process_object_result_deserialize() {
        let json = r#"{"bucket":"my-bucket","fileSize":3267,"object":"out.jpg","status":"OK"}"#;
        let result: ProcessObjectResult = serde_json::from_str(json).unwrap();
        assert_eq!(result.bucket, "my-bucket");
        assert_eq!(result.file_size, 3267);
        assert_eq!(result.object, "out.jpg");
        assert_eq!(result.process_status, "OK");
    }

